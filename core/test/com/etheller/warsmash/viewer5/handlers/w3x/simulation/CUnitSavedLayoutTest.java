	@Test
	void everyFieldOfTheUnitBeforeTheSplitStillHasOnePlace() {
		final List<Field> components = new ArrayList<>();
		for (final Field field : CUnit.class.getDeclaredFields()) {
			if (field.getAnnotation(SavedComponent.class) != null) {
				components.add(field);
			}
		}
		assertTrue(components.size() >= 15, "the unit's components: " + components);
		final Set<String> seen = new HashSet<>();
		for (final Field component : components) {
			for (final Field field : component.getType().getDeclaredFields()) {
				if (!Modifier.isStatic(field.getModifiers())) {
					assertTrue(seen.add(field.getName()), "two components have " + field.getName());
					assertFalse(declares(CUnit.class, field.getName(), null),
							"the unit and a component both have " + field.getName());
				}
			}
		}
		int moved = 0;
		for (final String entry : LEGACY_FIELDS.trim().split("\\s+")) {
			final String[] parts = entry.split("#");
			final boolean own = declares(CUnit.class, parts[0], parts[1]);
			boolean inComponent = false;
			for (final Field component : components) {
				inComponent |= declares(component.getType(), parts[0], parts[1]);
			}
			assertTrue(own ^ inComponent, entry + " has no single place now");
			if (inComponent) {
				moved++;
			}
		}
		assertTrue(moved > 120, "moved fields: " + moved);
	}

	private static boolean declares(final Class<?> type, final String name, final String typeName) {
		for (final Field field : type.getDeclaredFields()) {
			if (field.getName().equals(name) && ((typeName == null) || field.getType().getName().equals(typeName))) {
				return true;
			}
		}
		return false;
	}

